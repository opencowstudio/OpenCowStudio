import { addTemplate, createResolver, useLogger } from '@nuxt/kit'
import type { Nuxt } from 'nuxt/schema'
import { joinApiPaths } from '@opencowstudio/api-core'
import type { ApiControllerMetadata, ApiMethod } from '@opencowstudio/api-core'

const MODULE_NAME = '@opencowstudio/nuxt-api'

/** Alias through which generated handlers reach the dispatch helper. */
export const API_HANDLER_ALIAS = '#api-handler'

/** One Nitro handler entry produced from a scanned route. */
export interface ApiHandlerRegistration {
  /** Full route matched by Nitro, including the mount prefix. */
  route: string
  /** HTTP method the entry answers, upper-cased. */
  method: ApiMethod
  /** Absolute path of the generated handler module. */
  handler: string
}

/** Make a route path safe to use inside a generated file name. */
function toFileSegment(value: string): string {
  const segment = value.replace(/[^A-Za-z0-9]+/g, '_').replace(/^_+|_+$/g, '')
  return segment.length > 0 ? segment : 'root'
}

/**
 * Turn every scanned route into real Nitro handlers: one module per
 * `path + method` pair, so the Nitro router performs the matching (prefix tree,
 * method matching, path params) and each route is visible to Nitro like a
 * file-based one.
 *
 * Each generated module only names its controller class, its method and whether
 * that method declares the `ApiRequestContext` parameter; the actual request
 * handling is shared through `runtime/utils/handler.ts` (aliased as
 * `#api-handler`), which resolves the singleton controller instance from the
 * injected router and calls the method with the context only when declared.
 *
 * Build-time only — this helper must never be imported from the runtime.
 *
 * @param nuxt The Nuxt instance, used to register the templates and the alias.
 * @param controllers The resolved controller metadata.
 * @param prefix Mount prefix prepended to every route.
 * @returns One registration per generated handler, ready for `addServerHandler`.
 */
export function registerApiHandlers(
  nuxt: Nuxt,
  controllers: readonly ApiControllerMetadata[],
  prefix: string,
): ApiHandlerRegistration[] {
  const logger = useLogger(MODULE_NAME)
  const resolver = createResolver(import.meta.url)

  // Generated modules live in the build directory, so a relative import back
  // into the package would not resolve; the alias keeps them addressable.
  nuxt.options.alias[API_HANDLER_ALIAS] = resolver.resolve('../runtime/utils/handler')

  const registrations: ApiHandlerRegistration[] = []
  let index = 0

  for (const controller of controllers) {
    for (const route of controller.routes) {
      const fullPath = joinApiPaths(prefix, route.path)

      for (const method of route.methods) {
        // The index keeps file names unique even when different paths collapse
        // into the same segment (`/a-b` and `/a/b`).
        const filename = [
          'api-handlers',
          `${controller.className}.${route.handler}.${toFileSegment(route.path)}.${method.toLowerCase()}.${index++}.mjs`,
        ].join('/')

        const template = addTemplate({
          filename,
          write: true,
          getContents: () =>
            [
              '// This file is auto-generated by @opencowstudio/nuxt-api. Do not edit manually.',
              `import { createApiHandler } from '${API_HANDLER_ALIAS}'`,
              '',
              `export default createApiHandler(${JSON.stringify(controller.className)}, ${JSON.stringify(route.handler)}, ${route.injectsContext})`,
              '',
            ].join('\n'),
        })

        registrations.push({ route: fullPath, method, handler: template.dst })
      }
    }
  }

  logger.info(`Registered ${registrations.length} api route handler(s) on the Nitro router`)
  return registrations
}
