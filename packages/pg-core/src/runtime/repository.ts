// ---------------------------------------------------------------------------
// Entity operation contract + repository registry (runtime)
//
// `PgEntityRepository<T, K>` is the CRUD surface the runtime implements for a
// single entity. `PgRepositoryManager` owns that surface for every scanned
// entity: it is constructed with the `PgDataSourceManager` so each repository
// can resolve its datasource from the entity's `dbName`, and turns a metadata
// collection into the repository registry.
//
// Bootstrapping the registry also means bootstrapping the storage it needs:
// `createRepositories` first ensures every schema the entities live in exists,
// then every entity's table, before building the repositories themselves.
//
// Entity metadata resolution lives in `builder/parser.ts` (`parsePgEntity` /
// `parsePgEntities`), which is build-time only.
// ---------------------------------------------------------------------------

import { consola } from 'consola'
import { PgSqlTemplate } from './sql'
import type { PgDataSourceManager } from './datasource'
import type { PgEntityMetadata } from '../shared/types.ts'

// Tagged logger so the core stays framework-agnostic (no Nuxt dep).
const logger = consola.withTag('pg-repository')

/**
 * Entity operation contract: the common CRUD surface for a single entity.
 *
 * `T` is the entity class, `K` the type of its primary key value (`string` or
 * `number`). The key property is fixed to `id`.
 */
export interface PgEntityRepository<T, K = string | number> {
  /** Insert a new row; the key is generated by the database. */
  insert(data: Omit<T, 'id'>): Promise<T>

  /** Update the row whose key equals `id` and return the stored entity. */
  update(id: K, data: Omit<T, 'id'>): Promise<T>

  /** Delete the row whose key equals `id`. */
  delete(id: K): Promise<void>

  /** Return the row whose key equals `id`, or `null` when it does not exist. */
  findById(id: K): Promise<T | null>
}

/**
 * One column of a table as reported by the PostgreSQL catalog.
 *
 * Mirrors the columns selected by `PgSqlTemplate.COLUMN_DEFINITIONS`, so the
 * property names match the catalog's snake_case column aliases.
 */
export interface PgColumnDefinition {
  /** column name */
  column_name: string
  /** full SQL type, e.g. `double precision`, `timestamp with time zone` */
  data_type: string
  /** underlying type name, e.g. `float8`, `timestamptz` */
  udt_name: string
  /** column default expression, or `null` when the column has none */
  column_default: string | null
}

// ---------------------------------------------------------------------------
// PgRepositoryManager — the repository registry
//
// Holds one repository per entity. It never creates a connection of its own:
// the `PgDataSourceManager` handed to the constructor is the single source of
// pools, and each repository looks up its datasource through it.
// ---------------------------------------------------------------------------

/**
 * Repository registry for every scanned entity.
 *
 * Depends on the {@link PgDataSourceManager} at construction time; repositories
 * added through {@link PgRepositoryManager.createRepositories} resolve their
 * datasource from it via the entity's `dbName`.
 */
export class PgRepositoryManager {
  private readonly dataSources: PgDataSourceManager

  constructor(dataSources: PgDataSourceManager) {
    this.dataSources = dataSources
  }

  /**
   * Prepare the storage for `entities`, then create and register a repository
   * for each of them.
   *
   * The schemas are ensured first, so a table can assume its schema already
   * exists; every entity's table is then ensured (see
   * {@link PgRepositoryManager.ensureTable}) before its repository is built.
   *
   * @param entities The resolved entity metadata to build repositories from.
   */
  async createRepositories(entities: PgEntityMetadata[]): Promise<void> {
    await this.ensureSchemas(entities)

    for (const entity of entities) {
      await this.ensureTable(entity)
    }

    // Repository creation is not implemented yet.
  }

  /**
   * Read the column definitions of an entity's table.
   *
   * Runs {@link PgSqlTemplate.COLUMN_DEFINITIONS} against the entity's
   * datasource, binding the entity's schema and table. The query targets the
   * master node so the result reflects any DDL already applied during the same
   * bootstrap, rather than a possibly lagging replica.
   *
   * Returns one row per column in declaration order (the catalog is ordered by
   * `ordinal_position`), or an empty array when the table does not exist yet.
   *
   * @param entity The entity metadata whose table is introspected.
   */
  async getColumnDefinitions(entity: PgEntityMetadata): Promise<PgColumnDefinition[]> {
    const result = (await this.dataSources
      .get(entity.dbName)
      .query(PgSqlTemplate.COLUMN_DEFINITIONS, [entity.schema, entity.table])) as {
      rows: PgColumnDefinition[]
    }
    return result.rows
  }

  /**
   * Ensure the table backing an entity exists.
   *
   * Introspects the entity's table first (see
   * {@link PgRepositoryManager.getColumnDefinitions}): when it already has
   * columns, nothing is created. Otherwise the table is created from
   * {@link PgSqlTemplate.createTable} — the statement is `CREATE TABLE IF NOT
   * EXISTS`, so it stays safe if the table appears in between.
   *
   * @param entity The entity metadata whose table is ensured.
   */
  async ensureTable(entity: PgEntityMetadata): Promise<void> {
    const label = `"${entity.schema}"."${entity.table}"`
    logger.info(`Database "${entity.dbName}": ensuring table ${label} ...`)

    const existing = await this.getColumnDefinitions(entity)
    if (existing.length > 0) {
      logger.success(`Database "${entity.dbName}": table ${label} already exists`)
      return
    }

    await this.dataSources.get(entity.dbName).query(PgSqlTemplate.createTable(entity))
    logger.success(`Database "${entity.dbName}": table ${label} created`)
  }

  /**
   * Ensure every schema referenced by `entities` exists.
   *
   * The entities are grouped by `dbName` and the schema names within a database
   * are de-duplicated, so each datasource receives exactly one script that
   * creates all of its missing schemas. Every statement is idempotent, and the
   * script is sent as a single parameterless query, so it is applied over one
   * connection in one round trip.
   *
   * @param entities The resolved entity metadata to collect schemas from.
   */
  private async ensureSchemas(entities: PgEntityMetadata[]): Promise<void> {
    // dbName -> ordered, de-duplicated schema names.
    const schemasByDatabase = new Map<string, Set<string>>()
    for (const entity of entities) {
      let schemas = schemasByDatabase.get(entity.dbName)
      if (!schemas) {
        schemas = new Set<string>()
        schemasByDatabase.set(entity.dbName, schemas)
      }
      schemas.add(entity.schema)
    }

    for (const [dbName, schemas] of schemasByDatabase) {
      const names = [...schemas]
      const script = names
        .map(schema => PgSqlTemplate.createSchema(schema))
        .join(';\n')
      logger.info(`Database "${dbName}": ensuring schemas [${names.join(', ')}] ...`)
      await this.dataSources.get(dbName).query(script)
      logger.success(`Database "${dbName}": schemas ready [${names.join(', ')}]`)
    }
  }
}
