// ---------------------------------------------------------------------------
// Entity operation contract + repository registry (runtime)
//
// `PgEntityRepository<T, K>` is the CRUD surface the runtime implements for a
// single entity. `PgRepositoryManager` owns that surface for every scanned
// entity: it is constructed with the `PgDataSourceManager` so each repository
// can resolve its datasource from the entity's `dbName`, and turns a metadata
// collection into the repository registry.
//
// The registry itself is the module-level `repositories` map, keyed by the
// entity class (see `repositoryKey`), so a repository outlives the manager that
// built it and is shared by every caller.
//
// Bootstrapping the registry also means bootstrapping the storage it needs, but
// the DDL is not this module's concern: `createRepositories` drives the
// `SchemaSync` service (see `runtime/schema-sync.ts`) for the schemas and tables
// the entities declare, and only then builds and registers the repositories
// themselves.
//
// Entity metadata resolution lives in `builder/parser.ts` (`parsePgEntity` /
// `parsePgEntities`), which is build-time only.
// ---------------------------------------------------------------------------

import { SchemaSync } from './schema-sync'
import { PgStore } from './store-pg'
import { PgTableRepository } from './table-repository'
import type { PgDataSourceManager } from './datasource'
import type { FilterCondition } from './filter'
import type { SortCondition } from './sort'
import type { EntityMetadata } from '../shared/types.ts'

/**
 * One page of entities: the result of {@link PgEntityRepository.findPage}.
 *
 * `total` counts the entities the filter matched — the whole set the page was
 * cut from, not the number of items it carries — while `page`, `size` and
 * `items` describe the page itself: the 1-based number that was read (after
 * normalisation), how many entities a full page holds, and the entities of that
 * page in the requested order.
 *
 * `total` and `items` are read independently, so a page past the last one is
 * reported as an empty `items` list with `total` still set rather than as a
 * miss.
 */
export interface PageResult<T> {
  /** Number of entities matching the filter, across every page. */
  total: number

  /** 1-based number of the page that was read. */
  page: number

  /** How many entities a full page holds. */
  size: number

  /** The entities of the page, in sort order; empty when the page is past the last one. */
  items: T[]
}

/**
 * Entity operation contract: the common CRUD surface for a single entity.
 *
 * `T` is the entity class, `K` the type of its primary key value, which is
 * always a `string`. The key property is fixed to `id`.
 */
export interface PgEntityRepository<T, K extends string = string> {
  /** Insert a new row; the key is generated by the database. */
  insert(data: T): Promise<T>

  /** Update the row and return the stored entity. */
  update(data: T): Promise<T>

  /** Delete the row whose key equals `id`. */
  delete(id: K): Promise<void>

  /** Return the row whose key equals `id`, or `null` when it does not exist. */
  findById(id: K): Promise<T | null>

  /**
   * Return a set of entities, optionally narrowed and ordered.
   *
   * `size` is how many entities to read and `from` the position of the first
   * one; both are required and range-checked by the implementation: a `size`
   * outside `(0, 1000)` falls back to a page of 100, and a `from` outside
   * `[0, 100000)` falls back to the first entity. `filter` and `sort` are
   * optional — a filter names its column by property key (`createdAt`) or by
   * column name (`created_at`) — and a `from` past the last row yields an empty
   * list.
   */
  findMany(
    size: number,
    from: number,
    filter?: FilterCondition | null,
    sort?: SortCondition | null,
  ): Promise<T[]>

  /**
   * Return how many entities match `filter`, or every entity when it is
   * omitted.
   *
   * `filter` names its column by property key (`createdAt`) or by column name
   * (`created_at`), so it can be written against the entity shape; no match
   * counts `0` instead of reporting a miss.
   */
  count(filter?: FilterCondition | null): Promise<number>

  /**
   * Return one page of entities, optionally narrowed and ordered.
   *
   * The page is addressed by number instead of by position: `page` is 1-based
   * — page 1 being the first `size` entities — and `size` is how many entities
   * a page holds, so a caller pages through a result set without knowing about
   * `LIMIT` / `OFFSET`. Both are range-checked by the implementation: `page`
   * must be a whole number in `[1, 10000]` and falls back to the first page
   * otherwise, `size` must be a whole number in `[1, 1000]` and falls back to a
   * page of 100 otherwise — the same fallback policy
   * {@link PgEntityRepository.findMany} applies, so a caller can pass user
   * input straight through.
   *
   * The total is read first, with the same `filter`, and the page itself is read
   * only when that total is above zero; a filter matching nothing therefore
   * yields an empty page without a second round trip. A page past the last one
   * is reported as an empty `items` list with the total still set.
   *
   * `filter` names its column by property key (`createdAt`) or by column name
   * (`created_at`), exactly as in {@link PgEntityRepository.findMany} and
   * {@link PgEntityRepository.count}, so the total and the page always cover the
   * same set.
   */
  findPage(
    page: number,
    size: number,
    filter?: FilterCondition | null,
    sort?: SortCondition | null,
  ): Promise<PageResult<T>>
}

/**
 * Constructor of an entity class: the value bound to a class name in the
 * runtime `pgEntitiesTypeMap` of the generated entity manifest.
 *
 * Only the class identity matters here — it is the registry key — so the
 * signature accepts any constructable class and never instantiates one.
 */
export type PgEntityClass = abstract new (...args: never[]) => unknown

/** Entity classes keyed by their class name (`pgEntitiesTypeMap`). */
export type PgEntityTypeMap = Record<string, PgEntityClass>

// ---------------------------------------------------------------------------
// PgRepositoryManager — the repository registry
//
// Holds one repository per entity. It never creates a connection of its own:
// the `PgDataSourceManager` handed to the constructor is the single source of
// pools, and each repository looks up its datasource through it.
// ---------------------------------------------------------------------------

/**
 * Registry of every repository built so far, keyed by {@link repositoryKey}.
 *
 * Module-level — shared by every `PgRepositoryManager` instance — on purpose: a
 * repository is a stateless handle over a pooled datasource, so an entity has
 * exactly one handle per process rather than one per manager, and a lookup does
 * not need the manager that registered it. Registering an existing key replaces
 * the previous handle.
 */
const repositories = new Map<PgEntityClass, PgEntityRepository<unknown>>()

/**
 * Resolve the registry key of an entity: the class bound to its `className` in
 * the runtime entity type map.
 *
 * Keying by the class itself — instead of a `<dbName>.<schema>.<table>` string —
 * lets a caller look a repository up with the class it already holds.
 *
 * @param entity The entity metadata whose class is resolved.
 * @param entityTypes The entity classes keyed by class name (`pgEntitiesTypeMap`).
 * @throws When the type map carries no class for `entity.className`, i.e. the
 *         type map and the metadata do not come from the same scan.
 */
function repositoryKey(entity: EntityMetadata, entityTypes: PgEntityTypeMap): PgEntityClass {
  const entityClass = entityTypes[entity.className]

  if (!entityClass) {
    throw new Error(
      `No entity class found for "${entity.className}" (table "${entity.table}") in the entity type map.`,
    )
  }

  return entityClass
}

/**
 * Repository registry for every scanned entity.
 *
 * Depends on the {@link PgDataSourceManager} at construction time; repositories
 * built by {@link PgRepositoryManager.createRepository} — and, through it,
 * registered by {@link PgRepositoryManager.createRepositories} — resolve their
 * datasource from it via the entity's `dbName`.
 */
export class PgRepositoryManager {
  private readonly dataSources: PgDataSourceManager

  constructor(dataSources: PgDataSourceManager) {
    this.dataSources = dataSources
  }

  /**
   * Build the repository of one entity from its metadata.
   *
   * Three steps, each resolving the one before it:
   *
   *  1. the datasource the entity lives in, looked up by `dbName` through the
   *     manager's registry — so the entity is bound to its own database (master
   *     plus replicas) and not to a connection built here;
   *  2. the row-level store of that entity, a {@link PgStore} built from the
   *     metadata and that datasource;
   *  3. the entity-level repository, a {@link PgTableRepository} wrapping the
   *     store, which is what the caller receives.
   *
   * The manager creates no connection and holds no pool: every datasource comes
   * from the {@link PgDataSourceManager} it was constructed with, so a
   * repository built twice for the same entity shares one pool.
   *
   * `T` is the entity type the caller expects — the metadata is resolved at
   * build time and does not carry the class — so a caller that needs the typed
   * surface names it here, e.g. `createRepository<User>(metadata)`.
   *
   * @param entity The resolved entity metadata to build the repository from.
   * @returns The repository of the entity, backed by its plain table.
   */
  createRepository<T>(entity: EntityMetadata): PgEntityRepository<T> {
    const dataSource = this.dataSources.get(entity.dbName)
    const store = new PgStore<T>(entity, dataSource)

    return new PgTableRepository<T>(store)
  }

  /**
   * Prepare the storage for `entities`, then create and register a repository
   * for each of them.
   *
   * The storage is synchronized first, through a {@link SchemaSync} built from
   * the manager's datasource registry: every schema the entities live in is
   * ensured, so a table can assume its schema already exists, then every
   * entity's table (see {@link SchemaSync.ensureTable}) — which creates it or
   * reconciles its columns and indexes.
   *
   * Repository creation follows, once every table is in place: each entity's
   * repository (see {@link PgRepositoryManager.createRepository}) is registered
   * in the module-level registry under the entity class resolved from
   * `entityTypes` (see `repositoryKey`), so it is shared with, and reachable
   * by, every caller afterwards. An entity already registered is replaced by
   * its new handle.
   *
   * @param entities The resolved entity metadata to build repositories from.
   * @param entityTypes The entity classes keyed by class name, as exposed by the
   *   generated manifest's `pgEntitiesTypeMap`.
   */
  async createRepositories(
    entities: EntityMetadata[],
    entityTypes: PgEntityTypeMap,
  ): Promise<void> {
    const schemaSync = new SchemaSync(this.dataSources)
    await schemaSync.ensureSchemas(entities)

    for (const entity of entities) {
      await schemaSync.ensureTable(entity)
    }

    // Resolve every key before registering, so a missing class fails the whole
    // bootstrap instead of leaving the registry half populated.
    const keys = entities.map(entity => repositoryKey(entity, entityTypes))

    for (const [index, entity] of entities.entries()) {
      repositories.set(keys[index]!, this.createRepository(entity))
    }
  }
}

/**
 * Read side of the repository registry: resolves the repository of an entity
 * from the entity class itself.
 *
 * The registry is module-level and populated once, during startup, by
 * {@link PgRepositoryManager.createRepositories}. The service therefore holds no
 * state and creates nothing: it is a handle over what has already been
 * registered, safe to inject wherever the caller knows the entity class but not
 * the metadata behind it (for example the generated entity manifest's
 * `pgEntitiesTypeMap`).
 */
export class PgRepositories {
  /**
   * Return the registered repository of `entityClass`.
   *
   * The returned repository is typed by the class instance, so
   * `get(UserAccount)` yields a `PgEntityRepository<UserAccount>`.
   *
   * @param entityClass The entity class the repository was built for — one of
   *   the values of the manifest's `pgEntitiesTypeMap`.
   * @throws When no repository is registered for that class, i.e. the entity
   *         was not scanned or the registry was not bootstrapped.
   */
  get<C extends PgEntityClass>(entityClass: C): PgEntityRepository<InstanceType<C>> {
    const repository = repositories.get(entityClass)

    if (!repository) {
      throw new Error(
        `No repository registered for entity "${entityClass.name}". `
          + 'Repositories are registered during startup for every scanned entity.',
      )
    }

    return repository as PgEntityRepository<InstanceType<C>>
  }
}
