// ---------------------------------------------------------------------------
// Entity operation contract + repository registry (runtime)
//
// `PgEntityRepository<T, K>` is the CRUD surface the runtime implements for a
// single entity. `PgRepositoryManager` owns that surface for every scanned
// entity: it is constructed with the `PgDataSourceManager` so each repository
// can resolve its datasource from the entity's `dbName`, and turns a metadata
// collection into the repository registry.
//
// The registry itself is the module-level `repositories` map, keyed by the
// entity's `<dbName>.<schema>.<table>` (see `repositoryKey`), so a repository
// outlives the manager that built it and is shared by every caller.
//
// Bootstrapping the registry also means bootstrapping the storage it needs, but
// the DDL is not this module's concern: `createRepositories` drives the
// `SchemaSync` service (see `runtime/schema-sync.ts`) for the schemas and tables
// the entities declare, and only then builds and registers the repositories
// themselves.
//
// Entity metadata resolution lives in `builder/parser.ts` (`parsePgEntity` /
// `parsePgEntities`), which is build-time only.
// ---------------------------------------------------------------------------

import { SchemaSync } from './schema-sync'
import { PgStore } from './store-pg'
import { PgTableRepository } from './table-repository'
import type { PgDataSourceManager } from './datasource'
import type { PgEntityMetadata } from '../shared/types.ts'

/**
 * Entity operation contract: the common CRUD surface for a single entity.
 *
 * `T` is the entity class, `K` the type of its primary key value, which is
 * always a `string`. The key property is fixed to `id`.
 */
export interface PgEntityRepository<T, K extends string = string> {
  /** Insert a new row; the key is generated by the database. */
  insert(data: T): Promise<T>

  /** Update the row and return the stored entity. */
  update(data: T): Promise<T>

  /** Delete the row whose key equals `id`. */
  delete(id: K): Promise<void>

  /** Return the row whose key equals `id`, or `null` when it does not exist. */
  findById(id: K): Promise<T | null>
}

// ---------------------------------------------------------------------------
// PgRepositoryManager — the repository registry
//
// Holds one repository per entity. It never creates a connection of its own:
// the `PgDataSourceManager` handed to the constructor is the single source of
// pools, and each repository looks up its datasource through it.
// ---------------------------------------------------------------------------

/**
 * Registry of every repository built so far, keyed by {@link repositoryKey}.
 *
 * Module-level — shared by every `PgRepositoryManager` instance — on purpose: a
 * repository is a stateless handle over a pooled datasource, so an entity has
 * exactly one handle per process rather than one per manager, and a lookup does
 * not need the manager that registered it. Registering an existing key replaces
 * the previous handle.
 */
const repositories = new Map<string, PgEntityRepository<unknown>>()

/**
 * Build the registry key of an entity: `<dbName>.<schema>.<table>`.
 *
 * All three parts take part in the key, so two entities that share a table name
 * stay apart when they live in another schema or another database, while the
 * same entity always produces the same key.
 */
function repositoryKey(entity: PgEntityMetadata): string {
  return [entity.dbName, entity.schema, entity.table].join('.')
}

/**
 * Repository registry for every scanned entity.
 *
 * Depends on the {@link PgDataSourceManager} at construction time; repositories
 * built by {@link PgRepositoryManager.createRepository} — and, through it,
 * registered by {@link PgRepositoryManager.createRepositories} — resolve their
 * datasource from it via the entity's `dbName`.
 */
export class PgRepositoryManager {
  private readonly dataSources: PgDataSourceManager

  constructor(dataSources: PgDataSourceManager) {
    this.dataSources = dataSources
  }

  /**
   * Build the repository of one entity from its metadata.
   *
   * Three steps, each resolving the one before it:
   *
   *  1. the datasource the entity lives in, looked up by `dbName` through the
   *     manager's registry — so the entity is bound to its own database (master
   *     plus replicas) and not to a connection built here;
   *  2. the row-level store of that entity, a {@link PgStore} built from the
   *     metadata and that datasource;
   *  3. the entity-level repository, a {@link PgTableRepository} wrapping the
   *     store, which is what the caller receives.
   *
   * The manager creates no connection and holds no pool: every datasource comes
   * from the {@link PgDataSourceManager} it was constructed with, so a
   * repository built twice for the same entity shares one pool.
   *
   * `T` is the entity type the caller expects — the metadata is resolved at
   * build time and does not carry the class — so a caller that needs the typed
   * surface names it here, e.g. `createRepository<User>(metadata)`.
   *
   * @param entity The resolved entity metadata to build the repository from.
   * @returns The repository of the entity, backed by its plain table.
   */
  createRepository<T>(entity: PgEntityMetadata): PgEntityRepository<T> {
    const dataSource = this.dataSources.get(entity.dbName)
    const store = new PgStore<T>(entity, dataSource)

    return new PgTableRepository<T>(store)
  }

  /**
   * Prepare the storage for `entities`, then create and register a repository
   * for each of them.
   *
   * The storage is synchronized first, through a {@link SchemaSync} built from
   * the manager's datasource registry: every schema the entities live in is
   * ensured, so a table can assume its schema already exists, then every
   * entity's table (see {@link SchemaSync.ensureTable}) — which creates it or
   * reconciles its columns and indexes.
   *
   * Repository creation follows, once every table is in place: each entity's
   * repository (see {@link PgRepositoryManager.createRepository}) is registered
   * in the module-level registry under its `<dbName>.<schema>.<table>` key (see
   * `repositoryKey`), so it is shared with, and reachable by, every caller
   * afterwards. An entity already registered is replaced by its new handle.
   *
   * @param entities The resolved entity metadata to build repositories from.
   */
  async createRepositories(entities: PgEntityMetadata[]): Promise<void> {
    const schemaSync = new SchemaSync(this.dataSources)
    await schemaSync.ensureSchemas(entities)

    for (const entity of entities) {
      await schemaSync.ensureTable(entity)
    }

    for (const entity of entities) {
      repositories.set(repositoryKey(entity), this.createRepository(entity))
    }
  }
}
