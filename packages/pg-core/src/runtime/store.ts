// ---------------------------------------------------------------------------
// Entity store contract (runtime)
//
// `StoreProxy<T>` is the data-access contract of the runtime: the row
// primitives — insert, update, delete, a primary-key lookup, a paged read and a
// count — for a single entity. It holds no business concern: validation,
// lifecycle hooks and the pagination *policy* (which page to read, how to
// report a total) belong to the repository layer (`runtime/repository.ts`),
// which composes a store instead of replacing it.
//
// The contract is split from its implementations so the storage behind it can
// be swapped or stacked:
//
//   * `PgSqlEntityStore`    — the PostgreSQL implementation, issuing SQL through
//                             a `PgSqlExecutor` (a pooled datasource, or a
//                             transaction).
//   * a caching store       — a proxy that wraps another store and bridges it to
//                             a cache backend.
//
// Proxies depend only on this interface, never on a concrete store, so further
// concerns (metrics, tracing, auditing, …) can be layered on the same way.
//
// Entity metadata (the `@PgColumn` column mapping in particular) is produced at
// build time by `builder/parser.ts` and reaches the runtime as a plain
// `PgEntityMetadata` object; this module never imports the builder layer.
// ---------------------------------------------------------------------------

import type { PgFilterCondition } from './filter'
import type { PgSelectPageOptions } from './sql'
import type { PgEntityMetadata } from '../shared/types.ts'

/**
 * Data-access contract for a single entity: its row primitives.
 *
 * `T` is the entity type; the key property is fixed to `id` and its value is
 * always a `string` — the key column is declared as `TEXT` (see
 * `PgSqlTemplate.createTable`). An implementation owns the translation between
 * the entity shape (camelCase property names) and the storage shape (the
 * snake_case columns declared by `@PgColumn`).
 */
export interface StoreProxy<T> {
  /**
   * Insert a new row and return the stored entity.
   *
   * `row` is the record to write, and it carries `id` itself: the key is always
   * provided by the caller and never generated by the store. That keeps key
   * assignment in one place — the caller (typically the repository layer)
   * produces the key, the store only writes the row. The key column is declared
   * as `TEXT PRIMARY KEY` without a database default (see
   * `PgSqlTemplate.createTable`).
   */
  insert(row: T): Promise<T>

  /**
   * Update the row whose key equals `row.id` and return the stored entity.
   *
   * Full-record update: `row` is the complete new state of the record. Every
   * column declared by the entity metadata is written, so a property left out of
   * `row` is stored as `NULL` rather than kept — partial (per-field) updates
   * are not supported. The row is addressed by the `id` carried by `row`
   * itself, so the key is always part of the record.
   */
  update(row: T): Promise<T>

  /**
   * Delete the row whose key equals `id`.
   *
   * @returns whether a row was deleted — `false` when no row matched the key.
   */
  delete(id: string): Promise<boolean>

  /** Return the row whose key equals `id`, or `null` when it does not exist. */
  findById(id: string): Promise<T | null>

  /**
   * Return how many rows the entity holds, optionally narrowed by `filter`.
   *
   * `filter` is rendered into the `WHERE` clause, so the count covers exactly
   * the rows a filtered read would return; omitted (or `null`) it counts every
   * row of the entity. The count is an aggregate, so the result is the number
   * itself rather than a row: no match counts `0` instead of reporting a miss.
   */
  count(filter?: PgFilterCondition | null): Promise<number>

  /**
   * Return one page of the entity's rows, in the order `options.sort` asks for.
   *
   * `options` carries the whole page request: the filter driving the `WHERE`
   * clause, the sort driving `ORDER BY`, and the page size (`limit`) together
   * with the row offset (`offset`). Filter and sort are optional — without them
   * every row matches and the database order applies — while the two paging
   * values are required, so the size of the page is always the caller's
   * decision. An offset past the last row yields an empty list.
   *
   * The rows come back in the same shape {@link StoreProxy.findById} returns, so
   * a page and a primary-key lookup can be mapped the same way.
   */
  selectPage(options: PgSelectPageOptions): Promise<T[]>

  /**
   * Return the resolved entity metadata the store was built for: the database,
   * schema, table, key and columns its statements are derived from.
   *
   * The metadata is the store's identity — an implementation is bound to one
   * entity for its whole life — so a caller that only holds the contract (the
   * repository layer, a proxy stacked on another store) can read the mapping it
   * translates against without being handed it a second time.
   */
  getMetadata(): PgEntityMetadata
}
